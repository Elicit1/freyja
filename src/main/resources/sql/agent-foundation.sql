-- Agent foundation: additive, repeatable; does not modify existing business tables.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `agent_config` (
    `id` BIGINT NOT NULL,
    `create_by` BIGINT DEFAULT 0,
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    `update_by` BIGINT DEFAULT 0,
    `update_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    `deleted` TINYINT NOT NULL DEFAULT 0,
    `remark` VARCHAR(500),
    `agent_code` VARCHAR(64) NOT NULL,
    `display_name` VARCHAR(100) NOT NULL,
    `description` VARCHAR(500),
    `enabled` BOOLEAN NOT NULL DEFAULT FALSE,
    `provider_id` BIGINT,
    `model_code` VARCHAR(128),
    `system_prompt` MEDIUMTEXT,
    `model_options_json` JSON NOT NULL,
    `tool_policy_json` JSON NOT NULL,
    `skill_policy_json` JSON NOT NULL,
    `memory_policy_json` JSON NOT NULL,
    `runtime_policy_json` JSON NOT NULL,
    `avatar_config_json` JSON NOT NULL,
    `revision` INT NOT NULL DEFAULT 1,
    `profile_version` INT NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    UNIQUE KEY uk_agent_code (agent_code, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `agent_session` (
    `id` BIGINT NOT NULL,
    `create_by` BIGINT DEFAULT 0,
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    `update_by` BIGINT DEFAULT 0,
    `update_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    `deleted` TINYINT NOT NULL DEFAULT 0,
    `remark` VARCHAR(500),
    `agent_code` VARCHAR(64) NOT NULL,
    `drama_id` BIGINT,
    `title` VARCHAR(200) NOT NULL,
    `session_type` VARCHAR(24) NOT NULL,
    `test_request_id` VARCHAR(200),
    `summary` MEDIUMTEXT,
    `covered_through_seq` INT NOT NULL DEFAULT 0,
    `summary_version` INT NOT NULL DEFAULT 0,
    `next_seq` INT NOT NULL DEFAULT 1,
    `active_run_id` BIGINT,
    PRIMARY KEY (id),
    KEY idx_agent_session (session_type, update_time),
    UNIQUE KEY uk_agent_test_request (test_request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `agent_message` (
    `id` BIGINT NOT NULL,
    `create_by` BIGINT DEFAULT 0,
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    `update_by` BIGINT DEFAULT 0,
    `update_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    `deleted` TINYINT NOT NULL DEFAULT 0,
    `remark` VARCHAR(500),
    `session_id` BIGINT NOT NULL,
    `run_id` BIGINT,
    `seq` INT NOT NULL,
    `message_type` VARCHAR(32) NOT NULL,
    `model_role` VARCHAR(24),
    `content_json` JSON NOT NULL,
    `tool_call_id` VARCHAR(200),
    `client_request_id` VARCHAR(100),
    `event_type` VARCHAR(48),
    `read_at` DATETIME(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_agent_message_seq (session_id, seq),
    UNIQUE KEY uk_agent_client_request (session_id, client_request_id),
    KEY idx_agent_message_run (run_id, seq)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `agent_run` (
    `id` BIGINT NOT NULL,
    `create_by` BIGINT DEFAULT 0,
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    `update_by` BIGINT DEFAULT 0,
    `update_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    `deleted` TINYINT NOT NULL DEFAULT 0,
    `remark` VARCHAR(500),
    `session_id` BIGINT NOT NULL,
    `run_type` VARCHAR(24) NOT NULL,
    `objective` MEDIUMTEXT NOT NULL,
    `config_revision` INT NOT NULL,
    `profile_snapshot_json` JSON NOT NULL,
    `status` VARCHAR(24) NOT NULL,
    `model_turns` INT NOT NULL DEFAULT 0,
    `tool_calls` INT NOT NULL DEFAULT 0,
    `next_step_order` INT NOT NULL DEFAULT 1,
    `constraint_version` INT NOT NULL DEFAULT 0,
    `objective_message_id` BIGINT,
    `final_result_json` JSON,
    `error_message` TEXT,
    `cancel_requested` BOOLEAN NOT NULL DEFAULT FALSE,
    `lease_owner` VARCHAR(64),
    `lease_until` DATETIME(3),
    `lease_epoch` INT NOT NULL DEFAULT 0,
    `execution_millis` BIGINT NOT NULL DEFAULT 0,
    `prompt_tokens` INT NOT NULL DEFAULT 0,
    `completion_tokens` INT NOT NULL DEFAULT 0,
    `usage_unknown` BOOLEAN NOT NULL DEFAULT FALSE,
    `started_at` DATETIME(3),
    `finished_at` DATETIME(3),
    `read_at` DATETIME(3),
    PRIMARY KEY (id),
    KEY idx_agent_run_schedule (status, lease_until),
    KEY idx_agent_run_session (session_id, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `agent_step` (
    `id` BIGINT NOT NULL,
    `create_by` BIGINT DEFAULT 0,
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    `update_by` BIGINT DEFAULT 0,
    `update_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    `deleted` TINYINT NOT NULL DEFAULT 0,
    `remark` VARCHAR(500),
    `run_id` BIGINT NOT NULL,
    `logical_step_key` VARCHAR(200) NOT NULL,
    `parent_step_id` BIGINT,
    `step_order` INT NOT NULL,
    `step_type` VARCHAR(24) NOT NULL,
    `tool_name` VARCHAR(64),
    `tool_version` INT,
    `tool_call_id` VARCHAR(200),
    `provider_call_id` VARCHAR(200),
    `input_json` JSON,
    `result_json` JSON,
    `wait_handle_json` JSON,
    `status` VARCHAR(24) NOT NULL,
    `attempts` INT NOT NULL DEFAULT 0,
    `idempotency_key` VARCHAR(240),
    `constraint_version` INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_agent_logical_step (run_id, logical_step_key),
    KEY idx_agent_step_order (run_id, step_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `agent_memory` (
    `id` BIGINT NOT NULL,
    `create_by` BIGINT DEFAULT 0,
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    `update_by` BIGINT DEFAULT 0,
    `update_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    `deleted` TINYINT NOT NULL DEFAULT 0,
    `remark` VARCHAR(500),
    `scope_type` VARCHAR(24) NOT NULL,
    `scope_id` BIGINT NOT NULL,
    `memory_key` VARCHAR(100) NOT NULL,
    `content` TEXT NOT NULL,
    `source_message_id` BIGINT NOT NULL,
    `revision` INT NOT NULL DEFAULT 1,
    `enabled` BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    UNIQUE KEY uk_agent_memory (scope_type, scope_id, memory_key, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
